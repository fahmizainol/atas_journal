def test_matches_typescript():
    for name, pts, gold in (("SIGNAL", SIGNAL, SIGNAL_GOLD), ("NOISE", NOISE, NOISE_GOLD)):
        s = rp.score(pts)
        for k, want in gold.items():
            got = s[k]
            assert abs(got - want) < TOL, f"{name}.{k}: {got!r} != TS {want!r}"
    print("✓ scores match the TypeScript, luck included")


def test_tied_ranks():
    """Ties share the mean rank, or a KPI that plateaus (an occupancy pinned at 1.0
    for a week) silently scores on the order its days happened to arrive in."""
    got = rp.rank_corr([1, 1, 2, 2, 3, 3], [5, 5, 1, 9, 2, 2])
    assert abs(got - (-0.4923659639173309)) < TOL, got
    print("✓ tie handling matches the TypeScript")


def test_thin_sample_is_none():
    """Under six days a tercile is two days wide: there is nothing to rank, and
    saying so beats returning a confident number computed from four sessions."""
    assert rp.score(SIGNAL[:5]) is None
    assert rp.score(SIGNAL[:6]) is not None
    print("✓ thin samples decline to score")


def test_bands_partition_the_days():
    """Every day lands in exactly one band, and the outer two are what `edge`
    compares — if the bands lost or duplicated a day, `edge` would be quietly wrong
    rather than obviously broken.

    The bands carry no member list (see _band), so membership is checked the way a
    reader has to recover it: by the [lo, hi] value ranges, which must tile the
    days in order without overlapping.
    """
    s = rp.score(SIGNAL)
    lo, mid, hi = s["bands"]
    assert [b["band"] for b in s["bands"]] == ["low", "mid", "high"]
    assert lo["days"] == hi["days"] == len(SIGNAL) // 3
    assert lo["days"] + mid["days"] + hi["days"] == len(SIGNAL)
    assert lo["hi"] <= mid["lo"] and mid["hi"] <= hi["lo"]  # sorted, non-overlapping
    assert lo["lo"] == min(p["x"] for p in SIGNAL)
    assert hi["hi"] == max(p["x"] for p in SIGNAL)
    assert sum(b["trades"] for b in s["bands"]) == sum(p["trades"] for p in SIGNAL)
    assert abs((hi["avg_net"] - lo["avg_net"]) - s["edge"]) < TOL
    print("✓ bands partition the days and reproduce `edge`")


def test_constant_kpi_is_pure_luck():
    """A KPI with the same value every day explains nothing, and must not come back
    as ρ=0 with a suspiciously clean p-value."""
    flat = [{**p, "x": 0.5} for p in SIGNAL]
    s = rp.score(flat)
    assert s["rho"] == 0.0
    assert s["luck"] == 1.0
    print("✓ a constant KPI scores as pure noise")


def test_daily_pnl_rollup():
    """A trade belongs to the session it entered in; a win is a positive *net*
    (after commission), not a positive gross — the rollup the whole study joins on."""
    trades = pd.DataFrame([
        {"session": "2025-09-01", "net_pnl": 100.0},
        {"session": "2025-09-01", "net_pnl": -40.0},
        {"session": "2025-09-01", "net_pnl": 0.0},      # a scratch is not a win
        {"session": "2025-09-02T00:00:00", "net_pnl": 25.0},  # timestamped session
    ])
    by = rp.daily_pnl(trades)
    assert by["2025-09-01"] == {"net": 60.0, "trades": 3, "wins": 1}
    assert by["2025-09-02"] == {"net": 25.0, "trades": 1, "wins": 1}
    assert rp.daily_pnl(pd.DataFrame()) == {}
    print("✓ daily rollup buckets by entry session")


def test_luck_bar_tightens_with_the_family():
    """The bar has to move with how many KPIs were tried, or the board's best row is
    'significant' by construction."""
    assert rp.luck_threshold(20) < rp.luck_threshold(5) < 0.05 + TOL
    assert rp.expected_false_positives(20) == 1.0
    print("✓ the multiple-testing bar tightens with the family size")


