"""Regime-vs-P&L scoring: the Python must agree with the browser, to the bit.

The numbers in this module used to live only in frontend/src/lib/regimeStats.ts.
Now they are computed server-side and snapshotted, and the two implementations
have to produce the *same* answer — a permutation p-value that depends on who ran
it is not a p-value, and "the panel says 12% but the file says 14%" is a bug that
would take an afternoon to even notice.

So the fixtures below are golden: generated by running the real TypeScript under
node and freezing what it said. `luck` is the one that matters — it is the only
thing that pins the seeded mulberry32 port and the Fisher-Yates draw order, and a
strong-signal fixture can't test it (luck is 0 there no matter how wrong the RNG
is). Hence NOISE, whose 0.38 is a number only the exact draw sequence produces.

Regenerate (if regimeStats.ts ever legitimately changes):
    node -e 'import("./frontend/src/lib/regimeStats.ts").then(...)'

Run directly:  ``.venv/bin/python tests/test_regime_pnl.py``
"""

